"""Generate a deterministic roff manual from the actual argparse command tree."""

import argparse
from pathlib import Path
import textwrap

from tapediag.cli import parser


def roff(text):
    # Keep arbitrary help text from becoming a roff request or escape sequence.
    return "\n".join(("\\&" if line.startswith((".", "'")) else "") +
                     line.replace("\\", "\\e").replace("-", "\\-")
                     for line in text.splitlines())


def manual(program="tapediag"):
    if program == "dta":
        from tapediag.dta import parser as dta_parser
        root = dta_parser()
        description = "Plan by default. Maintenance requires --apply and interactive serial confirmation."
        name = "dta \\- guarded drive-test assistant"
    elif program == "tapediag":
        root = parser()
        description = "Dry-run is the default for collection. Offline analysis never opens a device."
        name = "tapediag \\- tape diagnostics and offline evidence analysis"
    else:
        raise ValueError("unknown manual program")
    out = ['.\\" Generated by scripts/generate-manpage.py; do not edit.',
           '.TH %s 1 "" "tapediag" "User Commands"' % program.upper(),
           ".SH NAME", name,
           ".SH DESCRIPTION", description,
           "The command help below is generated from argparse.",
           ".SH COMMAND LINE"]
    parsers = [(program, root)]
    for action in root._actions:
        if isinstance(action, argparse._SubParsersAction):
            parsers.extend((name, child) for name, child in action.choices.items())
    for name, command in parsers:
        command.formatter_class = lambda prog: argparse.HelpFormatter(prog, width=88)
        # argparse renamed this heading after 3.9; keep distributed bytes stable.
        command._optionals.title = "options"
        usage, _, body = command.format_help().partition("\n\n")
        # 3.9 wraps a long subcommand choice and its ellipsis differently.
        usage = textwrap.fill(" ".join(usage.split()), width=88, subsequent_indent="        ",
                              break_long_words=False, break_on_hyphens=False)
        out.extend([".SS " + roff(name), ".nf", roff(usage + "\n\n" + body), ".fi"])
    out.append(".SH EXIT STATUS")
    if program == "tapediag":
        out.extend(["Collection/report: 0 for planning or completed parsing, 1 for partial evidence, 2 for invalid input.",
                "Watch: 1 for regressions. Offline v4 analyses: 0 for completed analysis, 2 for invalid input.",
                "LTFS index: 0 for a valid index, 1 for error findings, 2 for refused or unreadable input.",
                "No exit status certifies hardware health."])
    else:
        out.extend(["0: plan or completed workflow. 1: restored workflow with evidence gaps.",
                    "2: invalid input, refusal or unresolved remote state. 130: interruption.",
                    "No exit status certifies hardware health; see the drive-test runbook."])
    out.extend([
                ".SH REFERENCES",
                "See the source documentation for public format citations and safety limits."])
    return "\n".join(out) + "\n"


def main():
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument("--program", choices=("tapediag", "dta"), default="tapediag")
    cli.add_argument("--output", type=Path, required=True)
    args = cli.parse_args()
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(manual(args.program), encoding="utf-8")
    print("argparse manual generated")


if __name__ == "__main__":
    main()
